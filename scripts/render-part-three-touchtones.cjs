const fs=require('node:fs'),path=require('node:path'),{spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'..'),output=path.resolve(root,'../outputs/part-three-strings-part-two-bass');
fs.mkdirSync(output,{recursive:true});
const catalog=JSON.parse(fs.readFileSync(path.join(root,'api/audio/halloween.json'),'utf8'));
const score=JSON.parse(fs.readFileSync(path.join(root,'api/audio/instruments/neon-countdown-score.json'),'utf8'));
catalog.touchtones.octaveShift=-4;
catalog.instruments['halloween-strings']=score.instruments['finale-horror-strings'];
catalog.touchtones.strings={gain:1.7,ringSeconds:0.25,decaySeconds:0.5,voicing:'bass-harmonics'};
catalog.instruments['halloween-idle-pulse']=score.instruments['midnight-pulse'];
catalog.touchtones.idleBell={pulse:true,timeoutSeconds:1,holdSeconds:1.2,volume:0.35};
const file=path.join(output,'preview-catalog.json');fs.writeFileSync(file,JSON.stringify(catalog,null,2));
const result=spawnSync(process.execPath,[path.join(__dirname,'render-halloween-audio.cjs'),output],{windowsHide:true,stdio:'inherit',env:{...process.env,HALLOWEEN_AUDIO_CATALOG:file}});
if(result.status!==0)process.exit(result.status||1);
const page=path.join(output,'index.html');
let html=fs.readFileSync(page,'utf8');
html=html.replaceAll('Cinematic Pulse Bass touchtones','Part 3 strings + Part 2 timeout bass');
const start=html.indexOf('<p>'),end=html.indexOf('</p>',start);
html=html.slice(0,start)+`<p>Recorded Part 3 tremolo strings over the low Cinematic Pulse Bass. Each chord follows the key's two bass pitches, using octaves and a fifth. After one second without another press, a single low Cinematic Pulse Bass note uses the actual Part 2 midnight-pulse preset, sustaining for 1.2 seconds before releasing. No bell.</p>`+html.slice(end+4);
fs.writeFileSync(page,html);console.log('Ready: '+page);
