import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={setTimeout,clearTimeout,Date};vm.runInNewContext(fs.readFileSync(new URL('../ValidatedCommandBuffer.js',import.meta.url),'utf8'),context);
const Buffer=context.ValidatedCommandBuffer;
const flush=async()=>{for(let i=0;i<20;i++)await Promise.resolve();};
let now=0,next=0;const timers=new Map(),events=[];
const buffer=new Buffer({now:()=>now,setTimer:(fn,delay)=>{const id=++next;timers.set(id,{fn,at:now+delay});return id;},clearTimer:id=>timers.delete(id),onChange:e=>events.push(e)});
const advance=async ms=>{now+=ms;for(const [id,t] of [...timers])if(t.at<=now){timers.delete(id);t.fn();}await flush();};
let releaseFirst,releaseSecond;const execution=[];
const first=buffer.enqueue({id:'a',ownerId:1,transcript:'ready',ttl:2000},async()=>{execution.push('a');await new Promise(r=>releaseFirst=r);return true;});
await flush();
const second=buffer.enqueue({id:'b',ownerId:2,transcript:'trip goal 110 percent',ttl:2000},async()=>{execution.push('b');await new Promise(r=>releaseSecond=r);return true;});
assert.equal(events.at(-1).text,'ready trip goal 110 percent','new capture components append while old work is blocked');
assert.equal(buffer.enqueue({id:'a',ownerId:1,transcript:'revised duplicate'},()=>{throw Error('duplicate ran');}),first,'one accepted component executes once');
assert.deepEqual(execution,['a']);
releaseFirst();await first;await flush();assert.deepEqual(execution,['a','b']);
await advance(5000);assert.equal(buffer.snapshot.length,2,'TTL cannot erase components while the buffer is processing');
releaseSecond();await second;await flush();await advance(1999);assert.equal(buffer.snapshot.length,2);await advance(1);assert.equal(buffer.snapshot.length,0,'TTL begins after pending work drains');
let release;let canceledRan=false,independentRan=false;
const active=buffer.enqueue({id:'c',ownerId:3,transcript:'first'},()=>new Promise(r=>release=r));await flush();
const canceled=buffer.enqueue({id:'d',ownerId:3,transcript:'invalid continuation'},()=>{canceledRan=true;return true;});
const independent=buffer.enqueue({id:'e',ownerId:4,transcript:'time'},()=>{independentRan=true;return true;});
buffer.cancelOwner(3);assert.equal(await canceled,false);assert(!buffer.snapshot.some(e=>e.ownerId===3),'cancel removes only the owned chain');
release(false);await active;await independent;assert(!canceledRan);assert(independentRan);
const skipped=await buffer.enqueue({id:'f',ownerId:4,transcript:'duplicate'},()=>Buffer.SKIPPED);
assert.equal(skipped,true);assert(!buffer.snapshot.some(e=>e.id==='f'),'duplicate guard skips do not remain in the transcript');
buffer.cancelAll();assert.equal(buffer.snapshot.length,0);assert.equal(timers.size,0);
await buffer.enqueue({id:'g',ownerId:5,chainId:'kept-root',transcript:'valid root'},()=>true);await flush();
let finishRoot;
const root=buffer.enqueue({id:'h',ownerId:5,chainId:'bad-root',transcript:'bad root'},()=>new Promise(r=>finishRoot=r));await flush();
buffer.cancelChain('bad-root');assert.equal(buffer.snapshot.map(e=>e.transcript).join(' '),'valid root','malformation does not remove an earlier independent root from the same utterance');
finishRoot(true);assert.equal(await root,false,'canceled active work cannot report success');
buffer.cancelAll();assert.equal(timers.size,0);
const failure=buffer.enqueue({id:'i',ownerId:6,transcript:'failed executor'},()=>{throw Error('executor failed');});
await assert.rejects(failure,/executor failed/);
assert.equal(await buffer.enqueue({id:'j',ownerId:7,transcript:'independent command'},()=>true),true,'executor rejection cannot poison later independent work');
buffer.cancelAll();
console.log('PASS validated buffer: ordered cross-capture work, duplicate protection, processing lifetime, idle TTL, owned cancellation and independent roots');
