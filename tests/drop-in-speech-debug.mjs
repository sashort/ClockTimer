import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const sandbox={setTimeout,clearTimeout};
vm.runInNewContext(fs.readFileSync(new URL('../DropInSpeechDebug.js',import.meta.url),'utf8'),sandbox);
const debug=sandbox.WMOFDropInSpeechDebug;
const source=new EventTarget(),stream=new EventTarget(),sent=[];
let login=false;
const doc={querySelector:s=>s==='#loginDialog[open]'?(login?{}:null):null,querySelectorAll:()=>[]};
Object.assign(stream,{publishing:true,speechDebugEnabled:false,broadcast:(type,payload)=>sent.push({type,payload})});
debug.attachPublisher(source,stream,doc);
debug.attachPublisher(source,stream,doc);
const emit=(name,detail)=>source.dispatchEvent(new CustomEvent(name,{detail}));
emit('speechRecognizerTranscript',{transcript:'commands',isFinal:true});
assert.equal(sent.length,0,'normal viewers do not enable diagnostic publication');
stream.speechDebugEnabled=true;
emit('speechRecognitionAlternatives',{utteranceId:1,selectedIndex:1,hypotheses:[
 {index:0,text:'what',confidence:9},{index:1,text:'commands',confidence:8}],secret:'not forwarded'});
assert.equal(sent.length,1,'listeners are installed once');
assert.equal(sent[0].payload.detail.alternatives[1].text,'commands');
assert.equal(sent[0].payload.detail.selectedIndex,1);
assert.equal(sent[0].payload.detail.secret,undefined);
emit('speechCommandBufferChanged',{entries:[{id:'1',commandId:'ready',status:'executing',transcript:'ready',dependencyIds:['before'],commandElement:{},arguments:['secret']}],pending:true});
assert.equal(sent[1].payload.detail.entries[0].status,'executing');
assert.equal(sent[1].payload.detail.entries[0].arguments,undefined);
emit('speechRecognizerTranscript',{transcript:'com'});
emit('speechRecognizerTranscript',{transcript:'commands'});
await new Promise(resolve=>setTimeout(resolve,130));
assert.equal(sent.length,3,'rapid partial updates are coalesced');
assert.equal(sent[2].payload.detail.transcript,'commands');
login=true;
emit('speechRecognizerTranscript',{transcript:'1234 5678',isFinal:true});
assert.equal(sent.length,3,'login credentials are excluded');
login=false;
emit('speechRecognizerTranscript',{transcript:'pending'});
stream.speechDebugEnabled=false;
stream.dispatchEvent(new Event('speechDebugChanged'));
await new Promise(resolve=>setTimeout(resolve,130));
assert.equal(sent.length,3,'disconnect clears pending text');
const logs=[];
debug.log(sent[0].payload,{targetUserId:42,console:{log:(...args)=>logs.push(args)}});
assert.equal(logs[0][1].detail.selectedIndex,1);
assert.equal(logs[0][1].detail.alternatives[1].text,'commands');
assert.equal(logs[0][1].targetUserId,42);
debug.log({event:'speechValueValidated',detail:{kind:'duration',components:{hours:1,minutes:5,seconds:0},inferred:{hours:false,minutes:false,seconds:true}}},
 {console:{log:(...args)=>logs.push(args)}});
assert.equal(logs[1][1].detail.componentDisplay.minutes,'5','spoken amount stays unbracketed');
assert.equal(logs[1][1].detail.componentDisplay.seconds,'[0]','defaulted zero is bracketed');
debug.log({event:'execute arbitrary command'},{console:{log:()=>assert.fail('unsupported event')}});
console.log('PASS Drop-In speech diagnostics: opt-in, alternatives, selection, buffer, coalescing, credential exclusion, disconnect and console logging');
