import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
const read=name=>JSON.parse(fs.readFileSync(new URL('../'+name,import.meta.url),'utf8'));
const catalog=read('api/audio/catalog.json'),song=catalog.songs['dark-eighties'];
const settings=read(song.approvedMix.settings);
const sample=catalog.instruments[song.instrument].samples[0];
const wav=fs.readFileSync(new URL('../'+sample.url,import.meta.url));
assert.equal(wav.toString('ascii',0,4),'RIFF');
assert.equal(wav.readUInt32LE(24),48000);
assert.equal((wav.length-44)/96000,130);
assert.equal(createHash('sha256').update(wav).digest('hex'),song.approvedMix.sha256);
assert.equal(settings.menuIcon,'pumpkin');
assert.equal(settings.clap.events.length,96);
assert.equal(settings.washboard.events.length,13);
assert(settings.clap.events.every(e=>e.beat%8===2||e.beat%8===6),'Claps follow snare beats');
assert(settings.washboard.events.every(e=>e.beat>=128 && e.beat<448));
const context=vm.createContext({document:{addEventListener(){}},console,fetch:async()=>({ok:true,json:async()=>catalog})});
vm.runInContext(fs.readFileSync(new URL('../api/audio/AudioEngine.js',import.meta.url),'utf8'),context);
const audio=context.WMOFAudio;
assert(Math.abs(audio.songTiming(song).durationMs-130000)<1e-6);
const events=audio.playbackEvents(song,120);
assert.equal(events.length,1);
assert.equal(events[0].sampleStartSeconds,32);
assert.equal(events[0].offset,'120');
assert(Math.abs(audio.songTiming(song,{startBeat:120}).durationMs-98000)<1e-6);
assert.equal(audio.playbackEvents(song,487.5).length,0);
assert.equal(song.events[0].offset,'0','Seek must not alter catalog');
const ordinary={bpm:120,events:[{offset:'0',tone:'C4',length:'1'},{offset:'4',tone:'D4',length:'1'}]};
assert.equal(audio.songTiming(ordinary,{startBeat:3}).durationMs,1000,'Ordinary note scheduling preserved');
const associations=read('lang/en-US/associations.json'),texts=read('lang/en-US/ui-text.json').texts;
const option=associations.selects['af44f0e0-01a0-57a7-9b13-d56b283ac0b8'].find(o=>o.value==='dark-eighties');
assert(option);assert.equal(texts[option.textId].text,'\u{1f383} Dark 80s');
assert.match(fs.readFileSync(new URL('../order-filler.html',import.meta.url),'utf8'),/<option value="dark-eighties"/);
console.log('PASS approved 130-second mix, exact checksum, clap/washboard placement, pumpkin selection and seek/resume timing');
