import assert from 'node:assert/strict';
import fs from 'node:fs';
import {randomUUID} from 'node:crypto';
import {Window} from './LanguageWindow.mjs';
const window=new Window();const pack=window.WMOFLanguagePack;
const first=window.document.createElement('speech-command'),second=window.document.createElement('speech-command');
pack.bindCommand(first,'readyAt');pack.bindCommand(second,'readyAt');
window.document.body.append(first,second);
assert.equal(first.getAttribute('speech-pattern'),pack.language.speech.commands.readyAt);
assert.notEqual(first.dataset.languageId,second.dataset.languageId);
assert.notEqual(first.dataset.speechPatternId,second.dataset.speechPatternId);
assert.equal(first.getAttribute('data-speech-pattern-definition'),second.getAttribute('data-speech-pattern-definition'));
pack.bindPreprocessor(first,'readyAt');assert.equal(first.getAttribute('speech-preproc-context'),'clock');assert.equal(first.getAttribute('speech-preproc-field'),'spokenTime');
const clone=first.cloneNode(true);window.document.body.append(clone);pack.identify(clone);
assert.notEqual(clone.dataset.languageId,first.dataset.languageId);assert.notEqual(clone.dataset.speechPatternId,first.dataset.speechPatternId);assert.notEqual(clone.dataset.speechPreprocId,first.dataset.speechPreprocId);
const patternId=pack.resources['speech-patterns'].language.speech.commands.readyAt;
const ruleId=pack.resources['speech-patterns'].patterns[patternId].preprocessorId;
const transformId=randomUUID();pack.resources['speech-patterns'].customRules[transformId]={id:transformId,kind:'replace',pattern:'half four',flags:'g',replacement:'04:30'};
pack.resources['speech-patterns'].preprocessors[ruleId].transforms=[transformId];
assert.equal(pack.preprocess('ready at half four',ruleId),'ready at 04:30');
// Instrument the private shadow root for inspection without changing production visibility.
window.eval(fs.readFileSync(new URL('../SpeechMicBar.js',import.meta.url),'utf8').replace('this.attachShadow({mode: "closed"})','this.attachShadow({mode: "open"})'));
const bar1=window.document.createElement('speech-mic-bar'),bar2=window.document.createElement('speech-mic-bar');window.document.body.append(bar1,bar2);
await window.happyDOM.whenAsyncComplete();
const roots=[bar1.shadowRoot,bar2.shadowRoot,bar1,bar2];
const elements=roots.flatMap(root=>[...root.querySelectorAll('[data-language-id]')]);
assert.ok(elements.length>20);assert.equal(new Set(elements.map(el=>el.dataset.languageId)).size,elements.length);
const commands=roots.flatMap(root=>[...root.querySelectorAll('[speech-pattern]')]);
assert.ok(commands.length>2);assert.equal(new Set(commands.map(el=>el.dataset.speechPatternId)).size,commands.length);
assert.ok(roots.every(root=>!root.innerHTML.includes('{{text:')));
await window.happyDOM.close();
console.log('PASS dynamic and cloned element/pattern/rule UUIDs, source associations, preprocessing transforms and language-backed shadow UI');
