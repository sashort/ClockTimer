import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const catalog=JSON.parse(fs.readFileSync(new URL('../api/audio/catalog.json',import.meta.url),'utf8'));
const context=vm.createContext({document:{addEventListener(){}},fetch:async()=>({ok:true,json:async()=>catalog,arrayBuffer:async()=>new ArrayBuffer(8)}),console});
vm.runInContext(fs.readFileSync(new URL('../api/audio/AudioEngine.js',import.meta.url),'utf8'),context);
const {OscillatorInstrument,ExpressiveInstrument}=context.WMOFInstrumentClasses;
for(const [name,definition] of Object.entries(catalog.instruments)) {
 if(definition.class==='expressive') continue;
 const model=OscillatorInstrument.from(definition);
 assert.equal(model.constructor,OscillatorInstrument,name+' remains legacy');
 assert.equal(model.forEvent({offset:'0',tone:'C4'},0.2),definition,'Legacy definitions are returned unchanged');
}
const model=OscillatorInstrument.from(catalog.instruments['steelpan-expressive']);
assert(model instanceof ExpressiveInstrument);
const event={offset:'1/2',tone:'C4'};
const soft=model.forEvent(event,0.2),hard=model.forEvent(event,1);
assert.equal(JSON.stringify(soft),JSON.stringify(model.forEvent(event,0.2)),'Seeded variation is reproducible');
assert.notEqual(soft.partials[3].gain,hard.partials[3].gain,'Velocity changes spectral balance');
assert.equal(soft.partials[0].envelope.decay,0.34);
assert.equal(soft.partials[4].envelope.decay,0.035);
assert.equal(soft.volume,2.4);
assert.equal(soft.noise.decay,0.012);
assert.equal(JSON.stringify(catalog.instruments['steelpan-expressive']).includes('__expressive'),false,'Per-strike shaping does not mutate definitions');
const calls=[];const param={setValueAtTime:(...a)=>calls.push(['set',...a]),linearRampToValueAtTime:(...a)=>calls.push(['linear',...a]),exponentialRampToValueAtTime:(...a)=>calls.push(['exp',...a])};
ExpressiveInstrument.envelope(param,{attack:0.002,decay:0.08,sustain:0,release:0.3},1,2,0.4);
assert(calls.some(call=>call[0]==='exp' && call[2]===1.082),'Mode decays independently before note end');
assert.deepEqual(calls.at(-1),['linear',0,2.3]);
assert.throws(()=>OscillatorInstrument.from({partials:[{ratio:1,envelope:{decay:-1}}]}),/Invalid expressive/);
assert.throws(()=>OscillatorInstrument.from({class:'unknown'}),/Unknown instrument class/);
assert.throws(()=>OscillatorInstrument.from({samples:[]}),/nonempty/);
let decoded=0;
const sampled=OscillatorInstrument.from({samples:[{url:'soft.wav',rootFrequency:440,maxVelocity:0.4},{url:'hard.wav',rootFrequency:440,minVelocity:0.41}]});
await sampled.prepare({decodeAudioData:async()=>{decoded++;return {duration:1};}});
await sampled.prepare({decodeAudioData:async()=>{decoded++;return {duration:1};}});
assert.equal(decoded,2,'Sample buffers are cached');
assert.equal(sampled.sampleFor(440,0.2,event).url,'soft.wav');
assert.equal(sampled.sampleFor(440,0.8,event).url,'hard.wav');
assert.throws(()=>sampled.sampleFor(440,0.405,event),/No sample layer/);
const hardQuiet=model.forEvent({...event,strikeStrength:1},0.2);
const hardLoud=model.forEvent({...event,strikeStrength:1},1);
assert.equal(hardQuiet.partials[3].gain,hardLoud.partials[3].gain,'Hit strength is independent of playback dynamic');
assert.equal(hardQuiet.__strikeStrength,1);
assert.throws(()=>model.forEvent({...event,strikeStrength:1.1},0.2),/Invalid expressive/);
assert.throws(()=>OscillatorInstrument.from({strikeStrength:-1}),/Invalid expressive/);
const defaultStrength=OscillatorInstrument.from({strikeStrength:0.8});
assert(defaultStrength instanceof ExpressiveInstrument);
assert.equal(defaultStrength.forEvent(event,0.2).__strikeStrength,0.8);
assert.equal(defaultStrength.forEvent({...event,strikeStrength:0.4},0.2).__strikeStrength,0.4);
assert.equal(sampled.sampleFor(440,sampled.forEvent({...event,strikeStrength:0.8},0.2).__strikeStrength,event).url,'hard.wav','Quiet playback still selects a hard recorded strike');
assert.throws(()=>OscillatorInstrument.from({samples:[{url:'flute.wav',rootFrequency:440,loopStart:0.5,loopEnd:0.4}]}),/Invalid sample sustain loop/);
const badLoop=OscillatorInstrument.from({samples:[{url:'flute.wav',rootFrequency:440,loopStart:0.2,loopEnd:2}]});
await assert.rejects(badLoop.prepare({decodeAudioData:async()=>({duration:1})}),/exceeds recording duration/);
const flute=catalog.instruments['easter-egg-lead-flute'];
assert(flute.samples.every(sample=>fs.existsSync(new URL('../'+sample.url,import.meta.url))));
assert(catalog.songs['chime-easter-egg'].scoreEvents.some(event=>event.instrument==='easter-egg-pulse-lead'));
assert(catalog.instruments['easter-egg-lead-shawm'].samples.every(sample=>fs.existsSync(new URL('../'+sample.url,import.meta.url))));
assert(catalog.songs['chime-easter-egg'].events.filter(event=>event.tone.includes('\\')).every(event=>event.instrument==='easter-egg-featured-slides'));
console.log('PASS legacy instrument identity, expressive dispatch, independent mode envelopes, velocity tone, reproducible variation, original gain and cached sample layers');

// Chorus must opt into expressive routing without changing legacy definitions.
const chorusModel=OscillatorInstrument.from(catalog.instruments['jx3p-inspired-lead']);
assert(chorusModel instanceof ExpressiveInstrument);
assert.throws(()=>OscillatorInstrument.from({chorus:{delay:0.01,depth:0.02}}),/depth must be less/);
assert.throws(()=>OscillatorInstrument.from({chorus:{wet:1.1}}),/Invalid expressive/);
assert.throws(()=>OscillatorInstrument.from({chorus:{rate:0}}),/Invalid expressive/);
console.log('PASS optional chorus dispatch and safe modulation limits');
