import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Window} from './LanguageWindow.mjs';
const w=new Window({url:'https://clock.example/drop-in.php'});
for(const file of ['MicrophoneControl.js','ObserverMicrophone.js'])w.eval(fs.readFileSync(new URL('../'+file,import.meta.url),'utf8'));
w.WMOFLanguagePack={text:id=>id};
const calls=[];const menu={started:true,muted:false,async sleep(){calls.push('sleep');this.muted=true;},async wake(){calls.push('wake');this.muted=false;}};
const control=w.WMOFMicrophoneControl;
assert.equal((await control.setEnabled(menu,false)).accepted,true);await control.setEnabled(menu,false);
assert.deepEqual(calls,['sleep'],'duplicate explicit command does not toggle back');
await control.setEnabled(menu,true);assert.deepEqual(calls,['sleep','wake']);
menu.started=false;assert.equal((await control.setEnabled(menu,true)).accepted,false);
assert.equal((await control.setEnabled(menu,'true')).accepted,false);
const button=w.document.createElement('button');w.document.body.append(button);
const messages=[];let reject=false,failed=0;
const stream={viewing:true,async sendToPublisher(type,payload){messages.push({type,...payload});if(reject)throw Error('denied');}};
const observer=new w.WMOFObserverMicrophone({button,stream,onFailure:()=>failed++,timeout:15});
observer.update(2,{started:true,muted:false});assert.equal(button.disabled,false);button.click();await Promise.resolve();
assert.equal(messages[0].type,'trainer.microphone');assert.equal(messages[0].enabled,false);assert.equal(button.dataset.muted,'true');assert.equal(button.disabled,true);
button.click();assert.equal(messages.length,1,'single flight');
observer.finish('stale',{accepted:true,started:true,muted:true});assert.equal(button.disabled,true);
observer.finish(messages[0].commandId,{accepted:true,started:true,muted:true});assert.equal(button.disabled,false);
button.click();observer.reset(3);observer.update(3,{started:true,muted:false});observer.finish(messages.at(-1).commandId,{accepted:true,started:true,muted:true});assert.equal(button.dataset.muted,'false','old target cannot change new target');
reject=true;button.click();await new Promise(setImmediate);assert.equal(failed,1);assert.equal(button.dataset.muted,'false','forwarding rejection rolls back');
reject=false;button.click();await new Promise(r=>setTimeout(r,25));assert.equal(failed,2);assert.equal(button.disabled,false,'missing publisher response times out');
observer.update(3,{started:false,muted:false});assert.equal(button.disabled,true,'off recognizer cannot remotely wake');
assert.match(w.document.head.textContent,/#dropInMicrophoneButton\[data-muted="true"\]::after/);
assert.match(w.document.head.textContent,/#e32636/,'same red slash as mic-bar');
assert(!w.document.head.textContent.includes(':host('),'observer CSS cannot retain shadow selectors');
observer.reset();await w.happyDOM.close();console.log('PASS shared mic sleep/wake, authorization failures, single-flight, timeout, off engine and stale target responses');
