import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={structuredClone};
vm.runInNewContext(fs.readFileSync(new URL('../SpeechRecognitionLedger.js',import.meta.url),'utf8'),context);
const ledger=new context.SpeechRecognitionLedger({streamId:'capture-1'});
const epoch=ledger.begin('utterance-1');
const words=[{word:'ready',startSample:19200,endSample:21600},{word:'at',startSample:21600,endSample:24000}];
ledger.submit('commands',{segmentId:'c1',text:'ready at',words,final:true},epoch);
ledger.submit('time',{segmentId:'t1',text:'eight',words:[{word:'eight',startSample:19200,endSample:24000}],final:true},epoch);
const head={id:'head',owner:'commands',kind:'commands',context:'scheduled-start-time',text:'ready at',validated:true,state:'locked',startSample:19200,endSample:24000};
const result=await ledger.arbitrate(async()=>[head]);
assert(result.committed);assert.equal(result.slots[0].position.streamId,'capture-1');
assert.equal(result.slots[0].position.startByte,76800);assert.equal(result.slots[0].position.endByte,96000);
assert.equal(result.slots[0].position.sampleFormat,'float32');
assert.equal(ledger.snapshot().sources.length,2,'competing interpretations remain separate from owned slots');
const number={id:'wrong',owner:'time',kind:'time',context:'scheduled-start-time',text:'eight',state:'locked',startSample:19200,endSample:24000};
assert.equal(ledger.commit(ledger.snapshot(),[number]).reason,'ownership-conflict','numeric guesses cannot steal the validated command head');
const value={id:'value',owner:'time',kind:'time',context:'scheduled-start-time',text:'four',state:'locked',startSample:24000,endSample:28000};
assert(ledger.commit(ledger.snapshot(),[head,value]).committed);
assert(ledger.commit(ledger.snapshot(),[head,{...value,text:'four twelve',endSample:32000}]).committed,'ownership does not seal an extendable value');
const complete=[{...head,state:'sealed'},{...value,text:'four twelve',endSample:32000,state:'sealed'}];
assert(ledger.commit(ledger.snapshot(),complete).committed);
assert.equal(ledger.commit(ledger.snapshot(),[complete[0],{...complete[1],text:'five twelve'}]).reason,'sealed-conflict');
let release;
const pending=ledger.arbitrate(async()=>{await new Promise(r=>release=r);return complete;});
ledger.submit('time',{segmentId:'t2',text:'five'},epoch);release();
assert.equal((await pending).reason,'stale-candidates','asynchronous arbitration fences changed hypotheses');
const snapshot=ledger.snapshot();ledger.submit('digits',{segmentId:'d1',text:'one'},epoch);
assert(ledger.commit(snapshot,complete,{dependencies:['commands']}).committed,'unrelated recognizers do not invalidate independent ownership');
const old=ledger.snapshot();ledger.begin('utterance-2');
assert.equal(ledger.commit(old,complete).reason,'stale-utterance');
assert.equal(ledger.submit('commands',{segmentId:'late',text:'wake'},epoch),false);
assert.throws(()=>ledger.commit(ledger.snapshot(),[{...head,position:{streamId:'different'}}]),/different stream/);
assert.throws(()=>ledger.commit(ledger.snapshot(),[{...head,validated:false}]),/requires validation/);
assert.throws(()=>ledger.submit('time',{segmentId:'bad',words:[{word:'four',startSample:-1,endSample:8}]}),/sample intervals/);
assert.throws(()=>ledger.commit(ledger.snapshot(),[head,{...value,startSample:23000}]),/overlaps/);
ledger.submit('time',{segmentId:'untimed',text:'four twelve'});
assert.equal(ledger.snapshot().sources[0].segments[0].position,null,'untimed interims have no invented byte range');
const pcm16=new context.SpeechRecognitionLedger({streamId:'pcm16',sampleFormat:'int16'});
assert.equal(pcm16.position(19200,24000).startByte,38400);
console.log('PASS stream/sample/byte positions, competing recognizers, contextual ownership, extendable values, sealing, async revisions and independent slots');

ledger.begin('forecast');
const forecastHead={...head,forecast:{kind:'time',context:'scheduled-start-time'}};
assert(ledger.commit(ledger.snapshot(),[forecastHead]).committed);
assert.equal(ledger.forecasts[0].kind,'time');assert.equal(ledger.forecasts[0].state,'unfilled');
assert.throws(()=>ledger.commit(ledger.snapshot(),[forecastHead,{...value,kind:'number'}]),/forecast/);
assert(ledger.commit(ledger.snapshot(),[forecastHead,value]).committed);assert.equal(ledger.forecasts[0].state,'filled');
console.log('PASS declared next-slot type forecasts reject another recognizer type');
ledger.begin('context-race');
let current=true,releaseContext;
const contextRace=ledger.arbitrate(async()=>{await new Promise(resolve=>releaseContext=resolve);return [head];},{isCurrent:()=>current});
current=false;releaseContext();
assert.equal((await contextRace).reason,'stale-context');
assert.equal(ledger.slots.length,0,'context changes must reject ownership before modifying the ledger');
console.log('PASS asynchronous context changes cannot commit obsolete ownership');
